#[cfg(test)]
mod tests {
    use super::*;

    /// Length is part of the protocol contract: the device parses a
    /// fixed-size capsule. Lock it in.
    #[test]
    fn init_hardcoded_9a_length() {
        assert_eq!(INIT_HARDCODED_9A.len(), 581);
    }

    /// Capsules across the upstream `blobs_*.py` files all share the
    /// same `06 02 00 00` magic header, suggesting it's the on-wire
    /// command / sub-command marker. Verify ours starts with it.
    #[test]
    fn init_hardcoded_9a_magic_header() {
        assert_eq!(&INIT_HARDCODED_9A[..4], &[0x06, 0x02, 0x00, 0x00]);
    }

    /// The blob is publicly observable from python-validity (MIT) but
    /// must not be silently truncated in source — verify a known byte
    /// near the end as an "I copied the whole thing" sanity check.
    #[test]
    fn init_hardcoded_9a_tail_byte() {
        assert_eq!(*INIT_HARDCODED_9A.last().unwrap(), 0xc4);
    }

    /// LED-control blobs are exactly 125 bytes per upstream
    /// `python-validity/sensor.py:32-43`. Earlier versions of this
    /// module padded them to 256 bytes — the device silently
    /// rejected the over-long body and the LED never glowed.
    #[test]
    fn glow_blobs_are_125_bytes() {
        assert_eq!(GLOW_START_SCAN.len(), 125);
        assert_eq!(GLOW_END_SCAN.len(), 125);
    }

    /// Both blobs share the `0x39` opcode (sensor LED control). The
    /// next bytes encode the colour-pattern parameters; those differ
    /// between start and end.
    #[test]
    fn glow_blobs_share_led_opcode() {
        assert_eq!(GLOW_START_SCAN[0], 0x39);
        assert_eq!(GLOW_END_SCAN[0], 0x39);
        assert_ne!(&GLOW_START_SCAN[1..6], &GLOW_END_SCAN[1..6]);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fm_3367_calibration_curve_is_strictly_decreasing() {
        // The blob is a per-pixel gamma response curve; one byte per
        // line of the calibration scan, hence `lines_per_calibration_data`
        // entries (0x70 = 112).
        let cal = FM_3367_001.calibration_blob;
        assert_eq!(cal.len(), FM_3367_001.lines_per_calibration_data as usize);
        for w in cal.windows(2) {
            assert!(
                w[0] >= w[1],
                "calibration curve must be decreasing: {:?}",
                w
            );
        }
        assert_eq!(cal[0], 0x9b);
        assert_eq!(*cal.last().unwrap(), 0x06);
    }

    #[test]
    fn fm_3367_geometry_is_consistent() {
        // bytes_per_line covers an 8-byte per-line header + line_width pixels.
        assert_eq!(FM_3367_001.line_width, 112);
        assert_eq!(FM_3367_001.bytes_per_line, 0x78);
        assert_eq!(FM_3367_001.bytes_per_line - FM_3367_001.line_width, 8);
    }

    #[test]
    fn lookup_by_type() {
        assert!(by_type(0x0199).is_some());
        assert!(by_type(0x0000).is_none());
    }

    /// The capture program is a stream of `<u16 type, u16 size, body>`
    /// chunks (see `crate::chunks`). Verify it parses fully with no
    /// trailing bytes.
    #[test]
    fn fm_3367_prog_is_well_formed_chunks() {
        let chunks = crate::chunks::split(&FM_3367_001_PROG).unwrap();
        // Upstream's program for our device produces a non-trivial
        // number of chunks — sanity floor.
        assert!(
            chunks.len() >= 8,
            "expected >=8 chunks, got {}",
            chunks.len()
        );
        // Re-merging should be byte-identical (round-trip).
        let merged = crate::chunks::merge(&chunks);
        assert_eq!(merged, FM_3367_001_PROG);
    }

    /// Verify the program contains the 0x34 "Timeslot Table 2D"
    /// chunk that `line_update_type_1` mutates per capture mode.
    /// Without this chunk, the line_update path is a no-op.
    #[test]
    fn fm_3367_prog_contains_timeslot_table() {
        let chunks = crate::chunks::split(&FM_3367_001_PROG).unwrap();
        let timeslot = chunks.iter().find(|c| c.kind == 0x0034);
        assert!(
            timeslot.is_some(),
            "expected a 0x34 Timeslot Table 2D chunk"
        );
        // The body must be at least line_width bytes — the second pass
        // through it slices `tst[line_width..]`.
        let body = &timeslot.unwrap().body;
        assert!(
            body.len() >= FM_3367_001.line_width as usize,
            "body shorter than line_width"
        );
    }

    /// Locked first chunks in upstream's program — these map to
    /// documented chunk types (0x20 = "Set Register 32", 0x32 =
    /// "Set Registers 16" per `timeslot.py:dump_all`).
    #[test]
    fn fm_3367_prog_starts_with_known_chunks() {
        let chunks = crate::chunks::split(&FM_3367_001_PROG).unwrap();
        assert_eq!(chunks[0].kind, 0x0023, "first chunk = 0x23 setup record");
        assert_eq!(chunks[0].body.len(), 0);
        assert_eq!(
            chunks[1].kind, 0x0020,
            "second chunk = 0x20 Set Register 32"
        );
        assert_eq!(chunks[1].body.len(), 8);
        assert_eq!(
            chunks[2].kind, 0x0032,
            "third chunk = 0x32 Set Registers 16"
        );
    }
}

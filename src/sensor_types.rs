//! Per-sensor-type calibration metadata required by the capture
//! pipeline. The layout mirrors upstream's `SensorTypeInfo` struct.

/// Static metadata for one Validity sensor variant.
#[derive(Debug, Clone)]
pub struct SensorTypeInfo {
    pub sensor_type: u16,
    /// On-wire bytes per scan line (header + pixel row).
    pub bytes_per_line: u16,
    pub repeat_multiplier: u16,
    pub lines_per_calibration_data: u16,
    /// Pixel width of one scan line, after stripping the per-line
    /// header bytes.
    pub line_width: u16,
    /// Per-pixel calibration / gamma curve, shipped from upstream
    /// `generated_tables.py`. Used during sensor open to seed the
    /// initial calibration state.
    pub calibration_blob: &'static [u8],
}

